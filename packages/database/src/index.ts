/**
 * Shared Prisma client singleton. Import from "@sylvara/database" in apps
 * and services to avoid connection-pool exhaustion in dev hot-reload.
 *
 * Prisma 7 requires an explicit driver adapter instead of a schema-embedded
 * connection URL.
 */
import { PrismaPg } from "@prisma/adapter-pg";
import { PrismaClient } from "@prisma/client";

const adapter = new PrismaPg({ connectionString: process.env.DATABASE_URL });

const globalForPrisma = globalThis as unknown as { prisma?: PrismaClient };

export const prisma =
  globalForPrisma.prisma ??
  new PrismaClient({
    adapter,
    log: process.env.NODE_ENV === "development" ? ["warn", "error"] : ["error"],
  });

if (process.env.NODE_ENV !== "production") globalForPrisma.prisma = prisma;

export * from "@prisma/client";
